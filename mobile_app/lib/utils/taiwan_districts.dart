/// 檢查「縣市＋行政區」是否為白名單內的合法組合。
bool isValidCityDistrict(String? city, String? district) {
  if (city == null || district == null) return false;
  final list = kTaiwanDistricts[city];
  if (list == null) return false;
  return list.contains(district);
}
