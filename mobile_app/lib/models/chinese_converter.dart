  /// 將字串轉換為台灣正體/繁體中文
  static String toTraditional(String input) {
    if (input.isEmpty) return input;
    String result = input;
    _phraseMap.forEach((simplified, traditional) {
      if (result.contains(simplified)) {
        result = result.replaceAll(simplified, traditional);
      }
    });
    final buffer = StringBuffer();
    for (final char in result.characters) {
      buffer.write(_charMap[char] ?? char);
    }
    return buffer.toString();
  }

  /// 轉換清單中所有字串為繁體中文
  static List<String> toTraditionalList(List<String> list) {
    return list.map((item) => toTraditional(item)).toList();
  }
